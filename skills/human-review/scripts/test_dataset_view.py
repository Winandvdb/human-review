#!/usr/bin/env python3
"""The Demo tab's dataset quick view: the 👁 in each chip of the DB Fixture row.

Two halves. `dataset_view.py` executes the project's own schema, seed and fixture SQL in
an in-memory SQLite and hands the page the rows; `dataset-view.js` draws an eye per fixture
in the DB Fixture row and, on a press, the tables side by side. The data half is tested on a small
repository written here in Postgres dialect — the constructs a real fixture uses
(`INSERT … SELECT … FROM (VALUES …) AS p(a, b) JOIN`, `DATE '…'`, `TRUNCATE … CASCADE`,
an `ALTER TABLE … ADD CONSTRAINT … FOREIGN KEY`) — and the drawing half in a browser.

Run with:  python3 -m pytest test_dataset_view.py
"""
from __future__ import annotations

import json
import subprocess
from pathlib import Path

import pytest

import dataset_view as dv

SCHEMA = """
CREATE TABLE types (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT);
CREATE INDEX ON types (name);
CREATE TABLE owners (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, last_name TEXT);
CREATE TABLE pets (
    id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name     TEXT,
    born     DATE,
    type_id  INT NOT NULL REFERENCES types (id),
    owner_id INT
);
ALTER TABLE ONLY public.pets
    ADD CONSTRAINT pets_owner_fk FOREIGN KEY (owner_id) REFERENCES public.owners(id);
CREATE TABLE users (username VARCHAR(20) PRIMARY KEY, enabled BOOLEAN NOT NULL DEFAULT TRUE);
"""
SEED = """
-- a comment; with a semicolon
TRUNCATE users, pets, owners, types RESTART IDENTITY CASCADE;
INSERT INTO types (name) VALUES ('cat'), ('dog');
INSERT INTO owners (last_name) VALUES ('O''Hara'), ('Holmes');
INSERT INTO pets (name, born, type_id, owner_id) VALUES
  ('Milton', DATE '2020-09-07', 1, 1), ('Toby', DATE '2020-11-27', 2, 2);
INSERT INTO users (username, enabled) VALUES ('admin', TRUE);
"""
GREEN = """
INSERT INTO owners (last_name) VALUES ('Weasley');
INSERT INTO pets (name, born, type_id, owner_id)
SELECT p.name, p.born, t.id, o.id
FROM (VALUES ('Scabbers', DATE '2014-07-31', 'cat'),
             ('Errol',    DATE '2012-03-01', 'dog')) AS p(name, born, type_name)
JOIN types  t ON t.name = p.type_name
JOIN owners o ON o.last_name = 'Weasley';
"""


@pytest.fixture
def repo(tmp_path: Path) -> Path:
    db = tmp_path / "backend" / "src" / "main" / "resources" / "db"
    for sub, name, text in (("migration", "V1__schema.sql", SCHEMA),
                            ("seed", "R__seed.sql", SEED),
                            ("fixtures", "green.sql", GREEN)):
        (db / sub).mkdir(parents=True, exist_ok=True)
        (db / sub / name).write_text(text, encoding="utf-8")
    subprocess.run(["git", "init", "-q", str(tmp_path)], check=True)
    subprocess.run(["git", "-C", str(tmp_path), "add", "."], check=True)
    return tmp_path


def test_statements_split_on_semicolons_outside_literals_and_comments():
    got = dv.split_sql("-- x; y\nSELECT 'a;b';\n/* ; */ SELECT $$ ; $$; SELECT 1")
    assert got == ["SELECT 'a;b'", "SELECT $$ ; $$", "SELECT 1"]


def test_a_values_list_with_a_column_alias_list_becomes_a_sqlite_subselect():
    [s] = dv._to_sqlite("SELECT p.a FROM (VALUES (1, DATE '2020-01-01')) AS p(a, d)")
    assert s == ("SELECT p.a FROM (SELECT column1 AS a, column2 AS d FROM "
                 "(VALUES (1, '2020-01-01'))) AS p")


def test_seed_rows_come_from_executing_the_seed(repo):
    data = dv.build(repo)
    assert data["skipped"] == []
    assert data["counts"][""] == {"owners": 2, "pets": 2, "types": 2, "users": 1}
    pets = data["sets"][""]["pets"]
    assert pets[0] == [1, "Milton", "2020-09-07", 1, 1]
    assert data["sets"][""]["owners"][0][1] == "O'Hara"
    # A BOOLEAN column reads as one, not as SQLite's 1.
    assert data["sets"][""]["users"] == [["admin", True]]


def test_a_fixture_is_the_seed_plus_its_rows_and_its_rows_are_marked(repo):
    data = dv.build(repo)
    green = data["sets"]["green"]
    # The INSERT … SELECT … JOIN computed its rows: two pets, both owned by the new owner.
    assert [r[1] for r in green["pets"]] == ["Milton", "Toby", "Scabbers", "Errol"]
    assert {r[4] for r in green["pets"][2:]} == {3}
    assert data["marks"]["green"] == {"pets": [2, 3], "owners": [2]}
    # A table the fixture did not touch is not repeated: the page falls back to the seed's.
    assert "types" not in green


def test_tables_are_ordered_by_outgoing_foreign_keys_first(repo):
    data = dv.build(repo)
    names = [t["name"] for t in data["tables"]]
    # pets points at owners (ALTER TABLE … FOREIGN KEY) and types (inline REFERENCES).
    assert names[0] == "pets"
    assert data["tables"][0]["fk"] == {"type_id": "types", "owner_id": "owners"}
    # Ties broken by how many tables point *at* it, then by name.
    assert names[1:] == ["owners", "types", "users"]


def test_no_seed_no_view(tmp_path):
    subprocess.run(["git", "init", "-q", str(tmp_path)], check=True)
    assert dv.build(tmp_path) is None
    assert dv.dataset_html(tmp_path) == ""
    assert dv.dataset_html(None) == ""


def test_a_statement_sqlite_cannot_run_is_skipped_and_named(repo):
    seed = repo / "backend/src/main/resources/db/seed/R__seed.sql"
    seed.write_text(SEED + "\nINSERT INTO owners (last_name) SELECT 'x' FROM generate_series(1, 3) g;\n")
    data = dv.build(repo)
    assert data["counts"][""]["owners"] == 2
    assert data["skipped"] and data["skipped"][0]["file"].endswith("R__seed.sql")


# ── the drawing half, in a browser ─────────────────────────────────────────────────────

BAR = ('<div class="appenv"><div class="appenv-run"><span class="appenv-title">Running app'
       '</span></div><div class="appenv-fixtures">'
       + "".join(f'<span class="appenv-fx" data-fixture="{n}"><span class="fx-dot"></span>'
                 f'<span class="appenv-fx-name">{n or "Default"}</span>'
                 f'<button type="button" class="appenv-reset" data-fixture="{n}"'
                 f' aria-disabled="true">Seed</button></span>'
                 for n in ("", "green", "unknown"))
       + '</div></div>')


@pytest.fixture(scope="module")
def browser():
    pw = pytest.importorskip("playwright.sync_api")
    with pw.sync_playwright() as p:
        try:
            b = p.chromium.launch()
        except Exception as e:                       # no chromium installed on this box
            pytest.skip(f"chromium unavailable: {e}")
        yield b
        b.close()


def _open(browser, data):
    page = browser.new_page()
    blob = json.dumps(data).replace("</", "<\\/")
    js = (dv._ASSETS / "dataset-view.js").read_text(encoding="utf-8")
    page.set_content(f'<div id="behaviour">{BAR}<script type="application/json" id="dsv-data">'
                     f'{blob}</script><script>{js}</script><video></video></div>')
    return page


def _big(repo):
    """The fixture repo, with a seed table long enough to fold."""
    seed = repo / "backend/src/main/resources/db/seed/R__seed.sql"
    seed.write_text(SEED + "INSERT INTO types (name) VALUES "
                    + ", ".join(f"('t{i}')" for i in range(12)) + ";\n")
    return dv.build(repo)


def test_every_fixture_the_data_knows_gets_an_eye_between_its_name_and_its_seed(browser, repo):
    """In the DB Fixture row, never in the Running app one: offline, the old eye was left
    hanging alone after Start (8 Oct 2026). A fixture with no data gets none."""
    page = _open(browser, dv.build(repo))
    assert page.eval_on_selector_all(".dsv-eye", "es => es.map(e => e.dataset.fixture)") \
        == ["", "green"]
    assert page.locator(".appenv-run .dsv-eye").count() == 0
    order = page.evaluate("""() => [...document.querySelector('.appenv-fx[data-fixture=green]')
        .children].map(c => c.className)""")
    assert order == ["fx-dot", "appenv-fx-name", "dsv-eye", "appenv-reset"]
    page.close()


def test_the_eye_opens_and_closes_that_fixtures_tables_and_does_not_reset(browser, repo):
    page = _open(browser, _big(repo))
    page.evaluate("""() => { window.RESETS = 0; document.querySelector('.appenv-fixtures')
        .addEventListener('click', ev => { if (ev.target.closest('.appenv-reset')) RESETS++; }); }""")
    page.click(".dsv-eye")
    panel = page.locator("#dsv-panel")
    assert panel.is_visible()
    assert page.evaluate("RESETS") == 0
    # The panel sits between the band and the video: it pushes the film down.
    assert page.evaluate("document.querySelector('.appenv').nextElementSibling.id") == "dsv-panel"
    seen = page.eval_on_selector_all(".dsv-t", "ds => ds.map(d => [d.querySelector('b')"
                                     ".textContent, d.open])")
    assert seen[0] == ["pets", True]
    # 14 types: more than ten rows, folded to its name and count until clicked.
    assert ["types", False] in seen
    types = page.locator(".dsv-t", has=page.locator("b", has_text="types"))
    assert types.locator("table").count() == 0
    types.locator("summary").click()
    types.locator("tbody tr").nth(13).wait_for()   # drawn on the (async) toggle event
    assert types.locator("tbody tr").count() == 14
    page.click(".dsv-eye")
    assert not panel.is_visible()
    page.close()


def test_a_fixture_opens_the_tables_it_added_to_with_its_rows_highlighted(browser, repo):
    page = _open(browser, _big(repo))
    assert page.evaluate("window.hrOpenDataset('green')") is True
    assert "green" in page.text_content(".dsv-title")
    assert page.locator("tr.dsv-new").count() == 3
    assert page.evaluate("window.hrOpenDataset('nope')") is False
    page.close()
